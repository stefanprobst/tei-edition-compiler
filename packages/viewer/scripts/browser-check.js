async page => {
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    const check = (condition, message) => { if (!condition) throw new Error(message); };
    // Synthetic image only for exercising UI success behavior; no corpus image is vendored.
    await page.route('https://iiif.acdh.oeaw.ac.at/**', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="100" height="120"><rect width="100" height="120" fill="#d9dfcf"/><text x="10" y="60" font-size="12">Test image</text></svg>' }));
    await page.goto('http://127.0.0.1:3000/');
    await page.locator('#navigation .document-button').first().waitFor();
    check(await page.locator('#navigation .document-button').count() === 3, 'Expected three documents');
    const initialReaderUrl = page.url();
    await page.locator('#navigation .document-button').nth(1).click();
    const secondReaderUrl = page.url();
    check(secondReaderUrl !== initialReaderUrl, 'Document navigation must create a history entry');
    await page.getByRole('button', { name: 'Document details & provenance' }).click();
    const inspectedReaderUrl = page.url();
    await page.goBack();
    check(page.url() === secondReaderUrl && (await page.locator('#inspector').innerText()).includes('Explore the document'), 'Back must restore document without selected record');
    await page.goBack();
    check(page.url() === initialReaderUrl && (await page.locator('h1').innerText()).includes('1963-05-12'), 'Back must return to the first document inside the app');
    await page.goForward();
    await page.goForward();
    check(page.url() === inspectedReaderUrl && (await page.locator('#inspector').innerText()).includes('1969-06-10'), 'Forward must restore inspector state');
    await page.reload();
    await page.locator('#navigation .document-button').first().waitFor();
    check(page.url() === inspectedReaderUrl && (await page.locator('#inspector').innerText()).includes('1969-06-10'), 'Reload must restore linked document and record');
    await page.locator('#navigation .document-button').first().click();

    await page.getByRole('button', { name: 'Page 3 · 2r', exact: true }).click();
    check(await page.getByRole('link', { name: 'Open image ↗', exact: true }).getAttribute('href') === 'https://iiif.acdh.oeaw.ac.at/iiif/images/amp/amp_0003.jp2/full/!1000,1000/0/default.jpg', 'Demo build must use the migrated image service at the real UI call site');
    const firstImage = page.locator('#inspector img');
    await firstImage.scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('#inspector img')].some(image => image.naturalWidth > 0));
    await page.getByRole('button', { name: 'Stella', exact: true }).first().focus();
    await page.keyboard.press('Enter');
    check((await page.locator('#inspector').innerText()).includes('Evidence at this position'), 'Keyboard activation must expose overlapping evidence');
    const choicesReaderUrl = page.url();
    await page.locator('#inspector').getByRole('button', { name: 'Stella', exact: true }).click();
    const mentionReaderUrl = page.url();
    await page.goBack();
    check(page.url() === choicesReaderUrl && (await page.locator('#inspector').innerText()).includes('Evidence at this position'), 'Back must restore overlapping-evidence choices');
    await page.goForward();
    check(page.url() === mentionReaderUrl && (await page.locator('#inspector blockquote').innerText()) === 'Stella', 'Forward must restore the selected occurrence');
    await page.getByRole('button', { name: 'Go to letter', exact: true }).click();
    check((await page.locator('#main .selected-evidence').allTextContents()).join('') === 'Stella', 'Go to passage must highlight the exact source range');
    const commentaryValue = await page.locator('.annotations select option').evaluateAll(options => options.find(option => option.label.startsWith('interpretation ·'))?.value);
    check(!!commentaryValue, 'Letter commentary must be discoverable');
    await page.locator('.annotations select').selectOption(commentaryValue);
    const commentary = await page.locator('#inspector').innerText();
    check(commentary.includes('International Rudolf Kassner Symposium') && commentary.includes('Certainty: high') && commentary.toLowerCase().includes('responsible contributors'), 'Commentary must retain interpretation, certainty and attribution');
    const contributorCount = await page.locator('#inspector > .record-link').count();
    check(contributorCount >= 3 && ['Grigoriou, Dimitra', 'Mayer, Sandra', 'Frühwirth, Timo'].every(name => commentary.includes(name)), 'Commentary must expose its three named contributors');
    await page.locator('#navigation .document-button').nth(1).click();
    check(await page.locator('#navigation .part-jump').filter({ hasText: 'poem' }).count() === 2, 'Compound object must retain both poem occurrences');
    check(await page.locator('#navigation').getByRole('button', { name: 'poem 1 of 2', exact: true }).count() === 1 && await page.locator('#navigation').getByRole('button', { name: 'poem 2 of 2', exact: true }).count() === 1, 'Repeated parts must have distinct occurrence labels');
    const textCheck = await page.evaluate(async () => {
        const edition = await (await fetch('/edition.json')).json();
        const documentData = edition.documents[1];
        return documentData.parts.every(part => {
            const element = [...document.querySelectorAll('[data-part-id]')].find(element => element.dataset.partId === part.id);
            const text = [...element.querySelectorAll(':scope > .transcription')].map(element => element.textContent).join('');
            return text === (part.content?.text ?? '').replaceAll('\uFFFC', '◇');
        });
    });
    check(textCheck, 'Rendered direct text must exactly preserve all part ranges');
    await page.locator('#navigation .document-button').nth(2).click();
    check(await page.locator('.transcription').count() === 0, 'Photograph must not fabricate text');
    const context = await page.locator('.context').innerText();
    check(['left side', 'right side', 'photographer', 'setting', '1970-09-22'].every(value => context.includes(value)), 'Photograph context must expose roles, setting and date');
    await page.locator('#main img').scrollIntoViewIfNeeded();
    await page.waitForFunction(() => [...document.querySelectorAll('#main img')].some(image => image.naturalWidth > 0));
    await page.getByRole('button', { name: 'Unlabelled person', exact: true }).first().click();
    check((await page.locator('#inspector').innerText()).includes('Canonical label unavailable'), 'Unknown authority labels must remain explicit');
    await page.locator('#inspector summary').filter({ hasText: 'Source evidence' }).click();
    check((await page.locator('#inspector a').allTextContents()).some(value => value.includes('canonical source')), 'Provenance needs explicit pinned source link');
    await page.unroute('https://iiif.acdh.oeaw.ac.at/**');
    await page.route('https://iiif.acdh.oeaw.ac.at/**', route => route.abort());
    await page.locator('#navigation .document-button').nth(0).click();
    await page.getByRole('button', { name: 'Page 1 · 1r', exact: true }).click();
    await page.locator('#inspector figure').scrollIntoViewIfNeeded();
    await page.locator('#inspector .image-error').waitFor({ state: 'visible' });
    await page.locator('#upload').setInputFiles('fixtures/synthetic/generic-edition.xml');
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Could not open file'));
    check(await page.locator('#navigation .document-button').count() === 3, 'Invalid upload must preserve current edition');
    await page.locator('#upload').setInputFiles('packages/viewer/dist/edition.json');
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('3 documents'));
    await page.getByRole('button', { name: 'Document details & provenance' }).click();
    await page.locator('#inspector summary').filter({ hasText: 'Source evidence' }).click();
    check((await page.locator('#inspector').innerText()).includes('No source link supplied'), 'Uploaded editions must not inherit demo source mappings');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#navigation .document-button').nth(2).click();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile view must not overflow horizontally');
    await page.screenshot({ path: '/tmp/tei-viewer-mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto('http://127.0.0.1:3000/');
    await page.locator('#navigation .document-button').nth(2).click();
    await page.screenshot({ path: '/tmp/tei-viewer-photograph.png', fullPage: true });
    check(!requests.some(url => url.split(/[?#]/)[0].endsWith('.xml')), 'Browser must not load XML');
    check(errors.length === 0, 'No browser runtime errors: ' + errors.join(', '));
    return { documents: 3, compoundPoemOccurrences: 2, textPreserved: true, keyboardInspection: true, imageSuccessAndFailure: true, uploadValidation: true, mobileOverflow: false, xmlRequests: 0, runtimeErrors: 0 };
}
