async page => {
    const check = (condition, message) => { if (!condition) throw new Error(message); };
    const errors = [], requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => requests.push(request.url()));
    await page.goto('http://127.0.0.1:3015/?edition=akademie');
    await page.locator('.candidate-choice').first().waitFor({ state: 'attached' });
    check(await page.locator('.candidate-choice').count() === 58, 'First meeting must expose all 58 choices');
    await page.locator('#navigation .document-button').nth(1).click();
    await page.waitForFunction(() => document.querySelector('#projection-status')?.textContent.startsWith('0 of 6'));
    check(await page.locator('.candidate-choice').evaluateAll(selects => selects.every(select => select.value === '')), 'No form may be chosen implicitly');
    const base = await (await page.request.get('http://127.0.0.1:3015/akademie-edition.json')).json();
    const study = await (await page.request.get('http://127.0.0.1:3015/akademie-alternatives.json')).json();
    check(base.version === '0.4' && study.version === '0.3', 'New contracts must be explicit');
    const groups = study.groups.filter(group => group.provenance.source === 'A_0058.xml');
    const group = groups[0];
    const abbreviated = group.candidates.find(candidate => candidate.role === 'abbreviated-form');
    const expanded = group.candidates.find(candidate => candidate.role === 'expanded-form');
    const original = await page.locator('.transcription').allTextContents();
    const control = page.locator('.candidate-choice').first();
    await page.locator('.reading-choice>summary').first().click();
    check((await page.locator('.reading-choice').first().innerText()).includes('no preferred reading'), 'Neutral roles must be explained');
    check((await page.locator('.reading-choice').first().innerText()).toLowerCase().includes('abbreviated form'), 'Abbreviated role must be visible');
    await control.selectOption(abbreviated.id);
    await page.waitForFunction(() => document.querySelector('#projection-status')?.textContent.startsWith('1 of 6'));
    check((await page.locator('.selected-candidate').innerText()) === 'P.', 'Written abbreviation mark must survive selection');
    check(await page.locator('.abbreviation-marker').count() === 3, 'Local abbreviation marks must be rendered');
    check(await page.locator('.superscript').count() === 3, 'Superscript letters must retain semantic rendering');
    const abbreviatedUrl = page.url();
    await control.selectOption(expanded.id);
    await page.waitForFunction(() => document.querySelector('.selected-candidate')?.textContent === 'pleno');
    const expandedUrl = page.url();
    check(expandedUrl !== abbreviatedUrl, 'Changing form must create a history entry');
    await page.goBack();
    await page.waitForFunction(() => document.querySelector('.selected-candidate')?.textContent === 'P.');
    await page.goForward();
    await page.waitForFunction(() => document.querySelector('.selected-candidate')?.textContent === 'pleno');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('.selected-candidate')?.textContent === 'pleno');
    check(JSON.stringify(await page.locator('.transcription').allTextContents()) === JSON.stringify(original), 'Base source view must remain unchanged');
    check((await page.locator('#projection-status').innerText()).includes('8 compiler diagnostics remain'), 'Base diagnostics must stay visible');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#reading-choices').scrollIntoViewIfNeeded();
    check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile controls must not overflow');
    await page.screenshot({ path: '/tmp/tei-abbreviation-mobile.png', fullPage: false });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#reading-choices').scrollIntoViewIfNeeded();
    await page.screenshot({ path: '/tmp/tei-abbreviation-desktop.png', fullPage: false });
    check(!requests.some(url => /\.xml(?:[?#]|$)/.test(url)), 'Browser must not request XML');
    check(errors.length === 0, 'Runtime errors: ' + errors.join(', '));
    return { all64Choices: true, noDefaultReading: true, abbreviatedAndExpanded: true, literalMarks: true, superscript: true, historyReload: true, baseUnchanged: true, mobileOverflow: false, xmlRequests: 0, runtimeErrors: 0 };
}
